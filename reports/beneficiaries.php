require_login();
$currentUser = current_user();
$db = getDB();

// Filters
$stateFilter  = sanitize($_GET['state'] ?? '');
$genderFilter = sanitize($_GET['gender'] ?? '');
$vulnFilter   = sanitize($_GET['vulnerability'] ?? '');
$statusFilter = sanitize($_GET['status'] ?? '');
$exportCsv    = isset($_GET['export']) && $_GET['export'] === 'csv';

$where = ["1=1"];
$params = [];

if (!empty($stateFilter)) {
    $where[] = "b.state = ?";
    $params[] = $stateFilter;
}

if (!empty($genderFilter)) {
    $where[] = "b.gender = ?";
    $params[] = $genderFilter;
}

if (!empty($vulnFilter)) {
    $where[] = "b.vulnerability_category = ?";
    $params[] = $vulnFilter;
}

if (!empty($statusFilter)) {
    $where[] = "b.verification_status = ?";
    $params[] = $statusFilter;
}

$whereClause = implode(" AND ", $where);

// Base query for report records
$query = "
    SELECT b.*, n.acronym as ngo_acronym, u.full_name as registered_by_name
    FROM beneficiaries b
    LEFT JOIN ngos n ON b.ngo_id = n.id
    LEFT JOIN users u ON b.registered_by = u.id
    WHERE {$whereClause}
    ORDER BY b.state ASC, b.county ASC, b.full_name ASC
";
$stmt = $db->prepare($query);
$stmt->execute($params);
$records = $stmt->fetchAll();

// Aggregates for report header
$totalHH = count($records);
$totalIndividuals = 0;
$totalChildrenU5 = 0;
$totalElderly = 0;
$totalPWD = 0;
$totalPregLact = 0;
$femaleHeadedCount = 0;

foreach ($records as $r) {
    $totalIndividuals  += (int)$r['household_size'];
    $totalChildrenU5   += (int)$r['children_under_5'];
    $totalElderly      += (int)$r['elderly_members'];
    $totalPWD          += (int)$r['disabled_members'];
    $totalPregLact     += (int)$r['pregnant_lactating'];
    if ($r['vulnerability_category'] === 'Female-Headed Household') {
        $femaleHeadedCount++;
    }
}

// Handle CSV Export
if ($exportCsv) {
    header('Content-Type: text/csv; charset=utf-8');
    header('Content-Disposition: attachment; filename="beneficiary_demographics_' . date('Ymd_His') . '.csv"');
    $output = fopen('php://output', 'w');
    fputcsv($output, [
        'Beneficiary ID', 'Full Name', 'Gender', 'Age', 'DOB', 'Contact Phone', 'Document Type', 'Document Number',
        'State', 'County', 'Payam/Boma', 'Community/Camp', 'HH Size', 'Children <5', 'Elderly (60+)',
        'PWD', 'Pregnant/Lactating', 'Vulnerability', 'Verification Status', 'Registration Date', 'NGO Partner'
    ]);
    foreach ($records as $r) {
        fputcsv($output, [
            $r['beneficiary_id'], $r['full_name'], $r['gender'], $r['estimated_age'], $r['date_of_birth'],
            $r['phone'], $r['id_document_type'], $r['id_document_number'], $r['state'], $r['county'],
            $r['payam_boma'], $r['community_camp'], $r['household_size'], $r['children_under_5'],
            $r['elderly_members'], $r['disabled_members'], $r['pregnant_lactating'], $r['vulnerability_category'],
            $r['verification_status'], $r['registration_date'], $r['ngo_acronym']
        ]);
    }
    fclose($output);
    exit();
}

