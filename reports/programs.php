require_login();
$currentUser = current_user();
$db = getDB();

$exportCsv = isset($_GET['export']) && $_GET['export'] === 'csv';

$query = "
    SELECT p.*, n.name as ngo_name, n.acronym as ngo_acronym,
           (SELECT COUNT(*) FROM program_enrollments pe WHERE pe.program_id = p.id) as enrolled_count,
           (SELECT COUNT(*) FROM aid_distributions ad WHERE ad.program_id = p.id) as distribution_count,
           (SELECT SUM(quantity) FROM aid_distributions ad WHERE ad.program_id = p.id) as total_quantity_distributed
    FROM aid_programs p
    JOIN ngos n ON p.ngo_id = n.id
    ORDER BY p.status = 'Active' DESC, p.id DESC
";
$programs = $db->query($query)->fetchAll();

// CSV Export
if ($exportCsv) {
    header('Content-Type: text/csv; charset=utf-8');
    header('Content-Disposition: attachment; filename="program_performance_' . date('Ymd_His') . '.csv"');
    $output = fopen('php://output', 'w');
    fputcsv($output, [
        'Program Code', 'Program Name', 'Implementing NGO', 'Sector / Category',
        'Target State', 'Target County', 'Target Goal (Beneficiaries)', 'Actual Enrolled',
        'Coverage Rate (%)', 'Total Distributions Handed Out', 'Total Units Disbursed', 'Unit', 'Status', 'Start Date', 'End Date'
    ]);
    foreach ($programs as $p) {
        $coverage = $p['target_beneficiaries'] > 0 ? round(($p['enrolled_count'] / $p['target_beneficiaries']) * 100, 1) : 0;
        fputcsv($output, [
            $p['program_code'], $p['name'], $p['ngo_acronym'], $p['category'],
            $p['target_state'], $p['target_county'], $p['target_beneficiaries'], $p['enrolled_count'],
            "{$coverage}%", $p['distribution_count'], $p['total_quantity_distributed'] ?? 0, $p['unit'], $p['status'], $p['start_date'], $p['end_date']
        ]);
    }
    fclose($output);
    exit();
}

